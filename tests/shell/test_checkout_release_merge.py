"""Exercise immutable checkout with real Git and regenerated tracked files."""

import os
import subprocess
from pathlib import Path

SCRIPT = Path(__file__).resolve().parents[2] / "scripts/release/checkout-release-merge.sh"


def test_dirty_generation_is_preserved_and_exact_tag_remains(tmp_path: Path) -> None:
    repo = tmp_path / "repo"
    repo.mkdir()

    def git(*args: str) -> str:
        return subprocess.check_output(["git", *args], cwd=repo, text=True).strip()

    git("init")
    git("config", "user.email", "test@example.com")
    git("config", "user.name", "Test")
    (repo / "openapi.json").write_text("old\n")
    git("add", ".")
    git("commit", "-m", "chore: previous generation")
    previous = git("rev-parse", "HEAD")
    (repo / "openapi.json").write_text("release bytes\n")
    git("commit", "-am", "chore: release")
    target = git("rev-parse", "HEAD")
    git("tag", "-a", "v12.2.2", "-m", "release")
    tag = git("rev-parse", "v12.2.2")
    git("checkout", "--detach", previous)
    (repo / "openapi.json").write_text("regenerated bytes\n")
    (repo / "unrelated.txt").write_text("retain\n")
    temp = tmp_path / "runner"
    temp.mkdir()
    subprocess.run(
        ["bash", str(SCRIPT), target],
        cwd=repo,
        env=os.environ | {"RUNNER_TEMP": str(temp)},
        check=True,
        capture_output=True,
        text=True,
    )
    assert git("rev-parse", "HEAD") == target
    assert git("rev-parse", "v12.2.2") == tag
    assert (repo / "openapi.json").read_text() == "release bytes\n"
    assert (repo / "unrelated.txt").read_text() == "retain\n"
    evidence = temp / "release-checkout-evidence"
    assert "regenerated bytes" in (evidence / "generated-tracked.patch").read_text()
    assert git("show", "stash@{0}:openapi.json") == "regenerated bytes"
